package opengraph

import (
	"bytes"
	"log/slog"
	"net/http"
	"strconv"
	"strings"
)

// maxBufferSize caps how much of a response body is buffered for injection.
// Larger bodies are passed through untouched.
const maxBufferSize = 1024 * 1024

// nolint:gochecknoglobals
var crawlerTokens = []string{
	"twitterbot",
	"facebookexternalhit",
	"discordbot",
	"slackbot",
	"telegrambot",
	"whatsapp",
	"googlebot",
	"bingbot",
	"applebot",
	"linkedinbot",
	"redditbot",
	"embedly",
	"vkshare",
	"yandex",
	"baiduspider",
	"duckduckbot",
	"pinterest",
	"quora link preview",
	"curl",
	"wget",
}

// isCrawler reports whether the given user agent belongs to a known crawler bot
// that renders social metadata previews.
func isCrawler(userAgent string) bool {
	if userAgent == "" {
		return false
	}

	lowerAgent := strings.ToLower(userAgent)
	for _, token := range crawlerTokens {
		if strings.Contains(lowerAgent, token) {
			return true
		}
	}

	return false
}

// Middleware injects resolved opengraph tags into html responses served to
// crawler bots. All other requests and responses are passed through untouched.
func (rep *Repository) Middleware(next http.Handler) http.Handler {
	return http.HandlerFunc(func(writer http.ResponseWriter, request *http.Request) {
		if !isCrawler(request.UserAgent()) || (request.Method != http.MethodGet && request.Method != http.MethodHead) {
			next.ServeHTTP(writer, request)

			return
		}

		buffer := &bufferingWriter{ResponseWriter: writer, request: request}
		next.ServeHTTP(buffer, request)
		buffer.finish(rep)
	})
}

// bufferingWriter wraps a ResponseWriter, buffering html responses long enough
// to inject the resolved opengraph tags into them. Any response that is not a
// small html body, or that streams as it is generated, is passed straight
// through to the underlying writer.
type bufferingWriter struct {
	http.ResponseWriter

	request *http.Request
	status  int
	buffer  bytes.Buffer
	// passThrough is set once the response is known to be incompatible with
	// buffering, after which all writes are delegated to the underlying writer.
	passThrough bool
	finalized   bool
}

func (b *bufferingWriter) WriteHeader(status int) {
	if b.status != 0 {
		return
	}

	b.status = status
	b.decide()
}

func (b *bufferingWriter) Write(payload []byte) (int, error) {
	if b.status == 0 {
		b.WriteHeader(http.StatusOK)
	}

	if b.passThrough {
		written, errWrite := b.ResponseWriter.Write(payload)

		return written, errWrite //nolint:wrapcheck
	}

	if b.buffer.Len()+len(payload) > maxBufferSize {
		// Bodies exceeding the cap are flushed verbatim, they are never fully
		// buffered.
		b.flushBuffered()

		written, errWrite := b.ResponseWriter.Write(payload)

		return written, errWrite //nolint:wrapcheck
	}

	written, errWrite := b.buffer.Write(payload)

	return written, errWrite //nolint:wrapcheck
}

// Flush delegates to the underlying writer, flushing anything buffered so far
// and degrading any remaining content to pass through, since responses streamed
// as they are generated cannot be safely injected into.
func (b *bufferingWriter) Flush() {
	b.flushBuffered()

	if flusher, ok := b.ResponseWriter.(http.Flusher); ok {
		flusher.Flush()
	}
}

// decide marks the response as pass through unless it is a 2xx html response.
// The content type is known to be set at this point for all html responses,
// generated by both the static file server and the SPA routes.
func (b *bufferingWriter) decide() {
	contentType := b.Header().Get("Content-Type")
	b.passThrough = b.status < 200 || b.status >= 300 || contentType == "" ||
		!strings.Contains(strings.ToLower(contentType), "text/html")

	if b.passThrough {
		b.ResponseWriter.WriteHeader(b.status)
	}
}

// flushBuffered moves anything buffered to the underlying writer verbatim and
// degrades the response to pass through, since content that has already been
// sent cannot be injected into. Without this, any writes following the flush
// would be buffered again and silently dropped by finish.
func (b *bufferingWriter) flushBuffered() {
	if b.passThrough || b.finalized {
		return
	}

	b.passThrough = true
	b.finalized = true

	if _, errWrite := b.buffer.WriteTo(b.ResponseWriter); errWrite != nil {
		slog.Warn("Failed to flush buffered response",
			slog.String("path", b.request.URL.Path), slog.String("error", errWrite.Error()))
	}
}

// finish injects the resolved tags into the buffered response once complete.
func (b *bufferingWriter) finish(rep *Repository) {
	if b.passThrough || b.finalized {
		return
	}

	// A handler that never wrote anything still needs a status decision so
	// that non html empty responses are not replaced with only meta tags.
	if b.status == 0 {
		b.WriteHeader(http.StatusOK)
	}

	if b.passThrough {
		return
	}

	b.finalized = true

	resolver, params, found := rep.resolve(b.request.URL.Path)

	var fn TagsFunc
	if found {
		fn = resolver
	}

	tags := rep.resolveTags(b.request.Context(), b.request, fn, params)

	body := inject(b.buffer.String(), render(tags, rep.siteName()))

	b.Header().Set("Content-Length", strconv.Itoa(len(body)))

	if _, errWrite := b.ResponseWriter.Write([]byte(body)); errWrite != nil {
		slog.Warn("Failed to write opengraph response",
			slog.String("path", b.request.URL.Path), slog.String("error", errWrite.Error()))
	}
}

func (rep *Repository) siteName() string {
	rep.mu.RLock()
	defer rep.mu.RUnlock()

	return rep.opts.SiteName
}
